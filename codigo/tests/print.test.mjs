import test from 'node:test';
import assert from 'node:assert/strict';
import {defaults,parseGcode,validateState} from '../dist/core.js';
import {bridgePreview,colorDistance,matchMaterial,remainingSeconds,sessionConsumedGrams,sessionTotalGrams,timeProgress} from '../dist/bridge-core.js';
import {migrate,beginPrintSession,advancePrintSession,finishPrintSession,stopPrintSession,discardPrintSession,reconcilePrintSessions,activePrintSessions,printHistory,printSession,stockItem,voidTransaction} from '../dist/workshop.js';
const near=(a,b)=>assert.ok(Math.abs(a-b)<1e-6,`${a} != ${b}`);
const fixture=()=>migrate(defaults());
const png='iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mP8z8BQDwAEhQGAhKmMIQAAAABJRU5ErkJggg==';
const thumb=`; thumbnail begin 16x16 92\n${png.match(/.{1,60}/g).map(x=>'; '+x).join('\n')}\n; thumbnail end`;

test('Cura headers expose time, per-filament grams and bounds without an engine',()=>{
 const r=parseGcode(';FLAVOR:Marlin\n;Generated with Cura_SteamEngine 5.13\n;TIME:7265\n;Filament used: 1.34122m, 0.25m\n;MINX:16.302\n;MAXX:56.302\n;MINY:3\n;MAXY:23\n;MINZ:0.2\n;MAXZ:10.2\n');
 assert.equal(r.source,'Cura');assert.equal(r.valid,true);near(r.minutes,7265/60);assert.equal(r.grams.length,2);
 near(r.grams[0],1341.22*Math.PI*(1.75/2)**2/1000*1.24);assert.deepEqual(r.dims,[40,20,10]);
});

test('Prusa, Orca and Bambu headers parse multiple grams, colors, layers and thumbnails',()=>{
 const r=parseGcode(`; generated by PrusaSlicer 2.8\n; filament used [g] = 23.5, 5.5\n; filament_colour = #4c6b51;#b76a4a\n; estimated printing time (normal mode) = 1d 2h 3m 4s\n;LAYER_COUNT:12\n;MAXZ:20\n;MINZ:0.2\n${thumb}`);
 near(r.minutes,1563+4/60);assert.deepEqual(r.grams,[23.5,5.5]);assert.deepEqual(r.colors,['#4c6b51','#b76a4a']);assert.equal(r.layers,12);assert.equal(r.source,'PrusaSlicer');
 assert.ok(r.thumbnail.startsWith('data:image/png;base64,iVBOR'));
 assert.equal(parseGcode(';TIME:3600').valid,false);
 assert.equal(parseGcode(';TIME:3600').minutes,60);
 assert.equal(parseGcode(';TIME:3600').valid,false);
});

test('Missing slicer bounds are measured from G-code movement',()=>{
 const r=parseGcode(';TIME:60\n;Filament used: 10g\nG21\nG90\nG1 Z0.2\nG1 X20 Y10\nG1 X5 Y30 Z4\n');
 assert.deepEqual(r.dims.map(v=>Math.round(v)),[20,30,4]);
});

test('Bridge preview matches a declared color and allows a manual replacement',()=>{
 const s=fixture(),data=parseGcode(';TIME:600\n;Filament used: 1m\n; filament_colour = #4c6b51\n');
 const pv=bridgePreview(data,'pieza.gcode',s.materials);
 assert.equal(pv.filaments.length,1);assert.equal(pv.filaments[0].matId,'forest');assert.equal(pv.filaments[0].matched,true);assert.ok(pv.filaments[0].grams>0);assert.equal(pv.valid,true);
 const manual=bridgePreview(data,'pieza.gcode',s.materials,{0:'ivory'});
 assert.equal(manual.filaments[0].matId,'ivory');assert.equal(manual.filaments[0].color,s.materials.find(m=>m.id==='ivory').color);
 assert.ok(colorDistance('#4c6b51','#4c6b51')===0);assert.equal(matchMaterial('#4c6b51',s.materials).id,'forest');
});

test('Print sessions consume inventory proportionally and never overdraw',()=>{
 const s=fixture(),forest=s.materials.find(m=>m.id==='forest'),before=forest.stock;
 const session=beginPrintSession(s,{name:'pieza.gcode',filaments:[{matId:'forest',grams:100,color:'#4c6b51'}],units:2,seconds:600,track:'time'});
 near(forest.stock,before);assert.equal(activePrintSessions(s).length,1);assert.equal(s.ledger.at(-1).type,'print');assert.equal(session.ledgerId,s.ledger.at(-1).id);
 advancePrintSession(s,session.id,.5);near(forest.stock,before-100);near(sessionConsumedGrams(session),100);near(sessionTotalGrams(session),200);
 advancePrintSession(s,session.id,.75);near(forest.stock,before-150);near(session.progress,.75);
 finishPrintSession(s,session.id,{completed:false,note:'prueba'});assert.equal(session.status,'stopped');near(forest.stock,before-150);
 assert.equal(activePrintSessions(s).length,0);assert.equal(printHistory(s)[0].id,session.id);assert.equal(printSession(s,session.id).status,'stopped');
});

test('Completing a print adds finished stock and voiding restores every movement',()=>{
 const s=fixture(),forest=s.materials.find(m=>m.id==='forest'),before=forest.stock;
 s.products.push({id:'fig',name:'Figura',sku:'F-1',sourceBoxId:'',sourceObjectId:'',stock:1,minStock:0,unitCost:25,packUnits:1,price:100,unit:'pzas'});
 const session=beginPrintSession(s,{name:'figura.gcode',filaments:[{matId:'forest',grams:10}],units:2,track:'manual'});
 advancePrintSession(s,session.id,.5);finishPrintSession(s,session.id,{completed:true,productId:'fig',qty:2});
 near(forest.stock,before-20);assert.equal(stockItem(s,'product','fig').stock,3);assert.equal(session.status,'completed');assert.ok(stockItem(s,'product','fig').unitCost>0);
 voidTransaction(s,session.ledgerId);near(forest.stock,before);assert.equal(stockItem(s,'product','fig').stock,1);assert.equal(stockItem(s,'product','fig').unitCost,25);assert.ok(session.voided);
});

test('Starting a print rejects insufficient stock and discarding only removes untouched sessions',()=>{
 const s=fixture(),forest=s.materials.find(m=>m.id==='forest'),stock=forest.stock;forest.stock=50;
 assert.throws(()=>beginPrintSession(s,{filaments:[{matId:'forest',grams:60}],units:1}),/Stock insuficiente/);forest.stock=stock;
 const session=beginPrintSession(s,{filaments:[{matId:'forest',grams:10}],units:1});
 assert.equal(s.printSessions.length,1);discardPrintSession(s,session.id);assert.equal(s.printSessions.length,0);assert.equal(s.ledger.length,0);
 const used=beginPrintSession(s,{filaments:[{matId:'forest',grams:10}],units:1});advancePrintSession(s,used.id,.1);
 assert.throws(()=>discardPrintSession(s,used.id),/consumió/);stopPrintSession(s,used.id);
});

test('Time progress stops at 99% and reconciliation interrupts stale USB sessions',()=>{
 const s=fixture();
 const session=beginPrintSession(s,{filaments:[{matId:'forest',grams:10}],seconds:100,track:'time'});
 const start=Date.parse(session.startedAt);
 near(timeProgress(session,start+50000),.5);near(remainingSeconds(session,start+50000),100);
 reconcilePrintSessions(s,{now:start+200000});near(session.progress,.99);assert.equal(session.status,'printing');
 const usb=beginPrintSession(s,{filaments:[{matId:'forest',grams:5}],track:'usb'});
 const old=Date.now()-120000;usb.updatedAt=new Date(old).toISOString();
 reconcilePrintSessions(s,{usbActive:false,now:Date.now()});assert.equal(usb.status,'interrupted');
 validateState(s);assert.equal(printSession(s,session.id).progress,.99);
});
